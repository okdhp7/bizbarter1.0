def guess_categories(text: str, top: int = 3) -> list[str]:
    # '대신 ~을 원합니다' 같은 교환 희망 부분은 제공 품목 분류에서 제외
    t = re.split(r"대신|교환으로|반대급부로|원하는\s*것", (text or "").lower())[0] or (text or "").lower()
    scored: list[tuple[int, str]] = []
    for cat, kws in KEYWORDS.items():
        hits = sum(len(k) for k in kws if k in t)   # 긴 키워드일수록 가중
        if hits:
            scored.append((hits, cat))
    scored.sort(key=lambda x: -x[0])
    return [c for _, c in scored[:top]]


def migrate_name(name: str, context: str = "") -> list[str]:
    """예전 분류명을 현재 분류로. '컨설팅/교육'처럼 갈라진 분류는 내용으로 판단(관심 분류는 둘 다)."""
    if name in CATALOG:
        return [name]
    if name == "컨설팅/교육":
        if not context:
            return ["경영·전문서비스", "교육·연구"]
        return ["교육·연구"] if re.search(r"교육|강의|연수|코칭|훈련", context) else ["경영·전문서비스"]
    if name in ("화학/소재", "원자재/부품", "생활/사무용품") and re.search(r"포장|완충|에어캡|뽁뽁이|박스|골판지", context):
        return ["생활사무·가구"]   # MasterBuy 기준: 포장·인쇄용품은 생활사무·가구
    if name == "기타":
        return guess_categories(context, 1) if context else []
    new = canonical_name(name)
    return [new] if new in CATALOG else []


